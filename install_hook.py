def _launch_gui(
    repo_root: Path,
    *,
    host: str = "127.0.0.1",
    port: int = 8765,
    no_open: bool = False,
    allow_remote: bool = False,
    timeout: int = 600,
    report_only: bool = False,
    report_path: Path | None = None,
) -> int:
    gui = get_install_dir(repo_root) / "gui_server.py"
    if not gui.is_file():
        gui = _TOOLKIT_DIR / "gui_server.py"
    if not gui.is_file():
        raise HookError("gui_server.py is missing; reinstall or update Commit Guard.")
    command = [
        sys.executable,
        str(gui),
        "--repo",
        str(repo_root),
        "--host",
        host,
        "--port",
        str(port),
        "--timeout",
        str(timeout),
    ]
    if no_open:
        command.append("--no-open")
    if report_only:
        command.append("--report-only")
    if report_path is not None:
        command.extend(["--report-path", str(report_path)])
    if allow_remote:
        command.append("--allow-remote")
    return subprocess.run(command, cwd=str(repo_root), check=False).returncode


def interactive_menu(default_path: str | None = None) -> None:
    print("\n" + "=" * 66)
    print("      🛡️   COMMIT GUARD — Interactive Manager")
    print("=" * 66)

    target_input = default_path or input("Target repository [Enter = current dir]: ").strip() or "."

    try:
        repo_root = find_repo_root(Path(target_input))
    except HookError as exc:
        print(f"\n❌ {exc}\n")
        return

    actions = {
        "1": ("Install / repair Commit Guard here", lambda: install(repo_root)),
        "2": ("Run a manual scan now", lambda: run_manual_scan(repo_root)),
        "3": ("Show status", lambda: status(repo_root)),
        "4": ("Diagnose problems (doctor)", lambda: doctor(repo_root)),
        "5": ("Write default .commit_guard.toml", lambda: init_config(repo_root)),
        "6": ("Disable auto-scan-on-commit", lambda: disable(repo_root)),
        "7": ("Enable auto-scan-on-commit", lambda: enable(repo_root)),
        "8": ("Update installed engine", lambda: update(repo_root)),
        "9": ("Uninstall completely", lambda: _confirm_uninstall(repo_root)),
        "g": ("Launch local web GUI", lambda: _launch_gui(repo_root)),
        "c": ("Change target repository", None),
        "0": ("Exit", None),
    }

    while True:
        print(f"\nTarget: {repo_root}")
        print("-" * 66)
        for key, (label, _) in actions.items():
            print(f"  [{key}] {label}")
        print("-" * 66)

        choice = input("Select an option: ").strip().lower()

        if choice == "0":
            print("Goodbye! 👋\n")
            return
        if choice == "c":
            new_input = input("New repository path: ").strip()
            if new_input:
                try:
                    repo_root = find_repo_root(Path(new_input))
                except HookError as exc:
                    print(f"❌ {exc}")
            continue
        action = actions.get(choice)
        if action and action[1] is not None:
            try:
                action[1]()
            except HookError as exc:
                print(f"❌ {exc}")
        else:
            print("Invalid choice.")


def _confirm_uninstall(repo_root: Path) -> None:
    confirm = input(f"Remove Commit Guard completely from {repo_root}? [y/N]: ").strip().lower()
    if confirm in ("y", "yes"):
        uninstall(repo_root)
    else:
        print("Aborted.")


