# Copying the toolkit
# --------------------------------------------------------------------------

_COPY_IGNORE = shutil.ignore_patterns("__pycache__", "*.pyc", ".rule_cache", "*.tmp")


def copy_toolkit(
    repo_root: Path,
    source_root: Path,
    force: bool = False,
    copy_docs: bool = True,
) -> Path:
    """Copies the engine into `<repo>/.commit_guard/`, self-contained."""
    install_dir = get_install_dir(repo_root)
    install_dir.mkdir(parents=True, exist_ok=True)

    source_root = Path(source_root).expanduser().resolve()
    if source_root == install_dir.resolve():
        print("  [install] Source is the already-installed copy — skipping file copy (repair mode).")
        return install_dir

    source_main = source_root / "main.py"
    source_core = source_root / "core"
    if not source_main.is_file() or not source_core.is_dir():
        raise HookError(
            f"'{source_root}' doesn't look like a Commit Guard toolkit "
            "(expected main.py and core/). Pass --source to point at the right directory."
        )

    shutil.copy2(source_main, install_dir / "main.py")
    source_install_hook = source_root / "install_hook.py"
    if source_install_hook.is_file():
        shutil.copy2(source_install_hook, install_dir / "install_hook.py")

    for gui_name in ("gui_server.py", "gui_actions.py", "gui_page.py"):
        source_gui = source_root / gui_name
        if source_gui.is_file():
            shutil.copy2(source_gui, install_dir / gui_name)

    dest_core = install_dir / "core"
    if dest_core.exists():
        shutil.rmtree(dest_core)
    shutil.copytree(source_core, dest_core, ignore=_COPY_IGNORE)
    print(f"  [install] Copied engine (main.py + core/) into {install_dir}")

    source_rules = source_root / "rules"
    dest_rules = install_dir / "rules"
    if source_rules.is_dir():
        if dest_rules.exists() and not force:
            print("  [install] Existing rules/ found — keeping as-is (pass --force to overwrite).")
        else:
            if dest_rules.exists():
                shutil.rmtree(dest_rules)
            shutil.copytree(source_rules, dest_rules, ignore=_COPY_IGNORE)
            print(f"  [install] Copied rules/ into {dest_rules}")
    elif not dest_rules.exists():
        print(
            f"  [install] WARNING: no rules/ directory found at '{source_root}' and "
            f"none is installed yet — scans will fail until rule files exist at {dest_rules}"
        )

    if copy_docs:
        for name in ("README.md", "docs"):
            source = source_root / name
            if not source.exists():
                continue
            destination = install_dir / name
            if destination.is_dir():
                shutil.rmtree(destination)
            elif destination.exists():
                destination.unlink()
            if source.is_dir():
                shutil.copytree(source, destination, ignore=_COPY_IGNORE)
            else:
                shutil.copy2(source, destination)

    return install_dir


def count_rule_files(rules_dir: Path) -> int:
    if not rules_dir.is_dir():
        return 0
    return sum(
        1
        for path in rules_dir.rglob("*")
        if path.is_file() and path.suffix.lower() in _RULE_FILE_SUFFIXES
    )


def _load_installed_ruleset(repo_root: Path):
    from core.rule_loader import load_ruleset

    install_dir = get_install_dir(repo_root)
    return load_ruleset(install_dir / "rules", warn=False, use_cache=True)


