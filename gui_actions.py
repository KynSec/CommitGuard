def _select_findings(report: dict, fingerprints: list[str] | None):
    findings = findings_from_report(report)
    if fingerprints is None:
        return findings
    wanted = {str(value) for value in fingerprints}
    if not wanted:
        raise ActionError("Select at least one finding to fix.")
    return [finding for finding in findings if finding.fingerprint in wanted]


def _outcome_dict(outcome) -> dict:
    return {
        "file": outcome.file,
        "line": outcome.line,
        "rule_id": outcome.rule_id,
        "before": outcome.before,
        "after": outcome.after,
        "applied": outcome.applied,
    }


def preview_fixes(
    target: str | Path,
    report: dict,
    fingerprints: list[str] | None = None,
    *,
    engine: str | Path | None = None,
) -> dict:
    repo = find_repo_root(target)
    engine_path = resolve_engine(repo, engine)
    ruleset, _ = load_ruleset(repo, engine_path)
    findings = _select_findings(report, fingerprints)
    from core.autofix import AutoFixError, apply_fixes

    try:
        result = apply_fixes(repo, findings, ruleset.rules, dry_run=True, restage=False)
    except AutoFixError as exc:
        raise ActionError(f"Could not preview fixes: {exc}") from exc
    fingerprint_by_location = {
        (finding.file, finding.line_number, finding.rule_id): finding.fingerprint
        for finding in findings
    }
    outcomes = []
    for item in result.outcomes:
        payload = _outcome_dict(item)
        payload["fingerprint"] = fingerprint_by_location.get(
            (item.file, item.line, item.rule_id), ""
        )
        outcomes.append(payload)
    return {
        "outcomes": outcomes,
        "files": sorted({item.file for item in result.outcomes}),
        "count": len(result.outcomes),
    }


def apply_fixes_action(
    target: str | Path,
    report: dict,
    fingerprints: list[str],
    *,
    engine: str | Path | None = None,
) -> dict:
    repo = find_repo_root(target)
    engine_path = resolve_engine(repo, engine)
    ruleset, _ = load_ruleset(repo, engine_path)
    findings = _select_findings(report, fingerprints)
    from core.autofix import AutoFixError, apply_fixes

    try:
        result = apply_fixes(repo, findings, ruleset.rules, dry_run=False)
    except AutoFixError as exc:
        raise ActionError(f"Could not apply fixes: {exc}") from exc
    return {
        "outcomes": [_outcome_dict(item) for item in result.outcomes],
        "files_modified": list(result.files_modified),
        "count": result.applied_count,
        "fixed_fingerprints": sorted(result.fixed_fingerprints),
    }


def inline_suggestions(
    target: str | Path,
    report: dict,
    *,
    engine: str | Path | None = None,
) -> dict:
    repo = find_repo_root(target)
    engine_path = resolve_engine(repo, engine)
    ruleset, _ = load_ruleset(repo, engine_path)
    findings = findings_from_report(report)
    from core.pr_creator import build_inline_suggestions

    suggestions = build_inline_suggestions(findings, ruleset.rules)
    return {
        "count": len(suggestions),
        "suggestions": [
            {
                "path": item.path,
                "line": item.line,
                "rule_id": item.rule_id,
                "body": item.body,
            }
            for item in suggestions
        ],
    }


def check_rules(
    target: str | Path,
    engine: str | Path | None = None,
    *,
    timeout: int = DEFAULT_TIMEOUT,
) -> dict:
    repo = find_repo_root(target)
    engine_path = resolve_engine(repo, engine)
    command = [sys.executable, str(engine_path), "--repo", str(repo), "--check-rules"]
    result = _run(command, cwd=repo, timeout=timeout)
    return {
        "exit_code": result.returncode,
        "output": _tail(f"{result.stdout}{result.stderr}"),
        "command": command,
    }


