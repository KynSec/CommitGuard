def _pr_command(
    engine: Path,
    repo: Path,
    report_path: Path,
    options: dict,
    extra: list[str],
) -> list[str]:
    command = build_scan_command(engine, repo, report_path, options)
    command.extend(extra)
    return command


def create_pr(
    target: str | Path,
    options: dict | None = None,
    *,
    token: str,
    repository: str | None = None,
    base: str | None = None,
    branch: str | None = None,
    title: str | None = None,
    engine: str | Path | None = None,
    timeout: int = DEFAULT_TIMEOUT,
) -> dict:
    repo = find_repo_root(target)
    engine_path = resolve_engine(repo, engine)
    if not token.strip():
        raise ActionError("A GitHub token is required to create a pull request.")
    slug = (repository or "").strip() or parse_github_slug(
        _git(repo, "remote", "get-url", "origin").stdout
    )
    if not slug or "/" not in slug:
        raise ActionError("Could not determine GITHUB_REPOSITORY (owner/repo).")
    opts = dict(options or {})
    extra = ["--create-pr"]
    if base:
        extra.extend(["--pr-base", base])
    if branch:
        extra.extend(["--pr-branch", branch])
    if title:
        extra.extend(["--pr-title", title])
    env = os.environ.copy()
    env["GITHUB_TOKEN"] = token.strip()
    env["GH_TOKEN"] = token.strip()
    env["GITHUB_REPOSITORY"] = slug
    with tempfile.TemporaryDirectory(prefix="commitguard-gui-pr-") as temp:
        report_path = Path(temp) / "report.md"
        command = _pr_command(engine_path, repo, report_path, opts, extra)
        result = _run(command, cwd=repo, env=env, timeout=timeout)
        output = f"{result.stdout}\n{result.stderr}"
        url_match = re.search(r"https://github\.com/[^\s]+/pull/\d+", output)
        number_match = re.search(r"PR #(\d+)", output)
        detail = {
            "exit_code": result.returncode,
            "stdout": _tail(result.stdout),
            "stderr": _tail(result.stderr),
            "command": command,
        }
        if result.returncode == 2:
            message = (result.stderr or result.stdout or "Could not create the pull request.").strip()
            raise ActionError(message.splitlines()[-1], detail=detail)
        return {
            **detail,
            "repository": slug,
            "url": url_match.group(0) if url_match else None,
            "number": int(number_match.group(1)) if number_match else None,
        }


def review_pr(
    target: str | Path,
    options: dict | None = None,
    *,
    token: str,
    repository: str | None = None,
    pr_number: int | str,
    engine: str | Path | None = None,
    timeout: int = DEFAULT_TIMEOUT,
) -> dict:
    repo = find_repo_root(target)
    engine_path = resolve_engine(repo, engine)
    if not token.strip():
        raise ActionError("A GitHub token is required to post a review.")
    try:
        number = int(pr_number)
    except (TypeError, ValueError) as exc:
        raise ActionError("A numeric pull request number is required.") from exc
    if number < 1:
        raise ActionError("A numeric pull request number is required.")
    slug = (repository or "").strip() or parse_github_slug(
        _git(repo, "remote", "get-url", "origin").stdout
    )
    if not slug or "/" not in slug:
        raise ActionError("Could not determine GITHUB_REPOSITORY (owner/repo).")
    env = os.environ.copy()
    env["GITHUB_TOKEN"] = token.strip()
    env["GH_TOKEN"] = token.strip()
    env["GITHUB_REPOSITORY"] = slug
    env["GITHUB_PR_NUMBER"] = str(number)
    with tempfile.TemporaryDirectory(prefix="commitguard-gui-review-") as temp:
        report_path = Path(temp) / "report.json"
        command = _pr_command(
            engine_path, repo, report_path, dict(options or {}), ["--review-pr"]
        )
        result = _run(command, cwd=repo, env=env, timeout=timeout)
        output = f"{result.stdout}\n{result.stderr}"
        posted = re.search(r"Posted (\d+) inline", output)
        skipped = re.search(r"\((\d+) suggestion", output)
        detail = {
            "exit_code": result.returncode,
            "stdout": _tail(result.stdout),
            "stderr": _tail(result.stderr),
            "command": command,
        }
        if result.returncode == 2:
            message = (result.stderr or result.stdout or "Could not post the review.").strip()
            raise ActionError(message.splitlines()[-1], detail=detail)
        return {
            **detail,
            "repository": slug,
            "pr": number,
            "posted": int(posted.group(1)) if posted else 0,
            "skipped": int(skipped.group(1)) if skipped else 0,
        }


