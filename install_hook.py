#!/usr/bin/env python3
"""
install_hook.py — Commit Guard lifecycle manager.

Running `install` COPIES the full engine (main.py + core/ + rules/ + docs/)
into the target repo under `<repo>/.commit_guard/`. The hook and the
`commit-guard` / `commit-guard.bat` wrappers all call that local copy, so
once installed a repo is fully self-contained: deleting or moving the
original toolkit has zero effect.

Subcommands:
    install     Copy the toolkit into a repo and wire up the hook.
    update      Refresh the installed engine (and rules with --force).
    uninstall   Remove everything Commit Guard put in a repo.
    enable      Re-enable a previously disabled hook.
    disable     Pause auto-scan-on-commit without uninstalling.
    status      Show what's installed, active rule count, and config state.
    doctor      Diagnose git/Python/rules/hook problems.
    init        Write a commented .commit_guard.toml template.
    scan        Run a manual scan without committing.
    check-rules Validate rules and the positive/negative corpus.
    explain     Show one rule's details.
    suppressions Audit baseline entries for expiry/staleness.
    gui         Launch the local web control center.

Run with no subcommand for an interactive menu.
"""

from __future__ import annotations

import argparse
import shlex
import shutil
import stat
import subprocess
import sys
from pathlib import Path

_TOOLKIT_DIR = Path(__file__).resolve().parent
if str(_TOOLKIT_DIR) not in sys.path:
    sys.path.insert(0, str(_TOOLKIT_DIR))

_INSTALL_DIRNAME = ".commit_guard"
_HOOK_NAME = "pre-commit"
_DISABLED_HOOK_NAME = "pre-commit.disabled"
_BACKUP_HOOK_NAME = "pre-commit.bak"
_PRE_PUSH_HOOK_NAME = "pre-push"
_DISABLED_PRE_PUSH_HOOK_NAME = "pre-push.disabled"
_BACKUP_PRE_PUSH_HOOK_NAME = "pre-push.bak"
_WRAPPER_SH_NAME = "commit-guard"
_WRAPPER_BAT_NAME = "commit-guard.bat"
_HOOK_MARKER = "Auto-generated by Commit Guard"

try:
    from core.rule_loader import RuleLoadError
except ImportError:  # pragma: no cover - core is always installed
    RuleLoadError = OSError  # type: ignore[assignment,misc]

_RULE_FILE_SUFFIXES = (".toml", ".yaml", ".yml", ".conf")
GITIGNORE_ENTRIES = (
    "# Commit Guard (local security scanner) — safe to delete anytime",
    f"{_INSTALL_DIRNAME}/*",
    f"!{_INSTALL_DIRNAME}/triage.yaml",
    "commit_guard_reports/",
    f"{_WRAPPER_SH_NAME}",
    f"{_WRAPPER_BAT_NAME}",
)


class HookError(RuntimeError):
    """Raised when an operation fails."""


# --------------------------------------------------------------------------
# Path resolution
# --------------------------------------------------------------------------

def _run_git(repo_root: Path, *args: str) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            ["git", *args],
            cwd=str(repo_root),
            capture_output=True,
            text=True,
            check=False,
        )
    except FileNotFoundError as exc:
        raise HookError("git executable not found on PATH.") from exc


def find_repo_root(target_path: Path) -> Path:
    target_path = Path(target_path).expanduser().resolve()
    if not target_path.exists():
        raise HookError(f"Target path does not exist: {target_path}")
    result = _run_git(target_path, "rev-parse", "--show-toplevel")
    if result.returncode != 0:
        raise HookError(f"'{target_path}' does not appear to be inside a git repository.")
    return Path(result.stdout.strip()).resolve()


def find_git_dir(target_path: Path) -> Path:
    target_path = Path(target_path).expanduser().resolve()
    result = _run_git(target_path, "rev-parse", "--git-dir")
    if result.returncode != 0:
        raise HookError(f"'{target_path}' does not appear to be inside a git repository.")
    git_dir = Path(result.stdout.strip())
    if not git_dir.is_absolute():
        git_dir = (target_path / git_dir).resolve()
    return git_dir


def find_hooks_dir(repo_root: Path) -> Path:
    """
    Honors `core.hooksPath` (including monorepos and shared hook folders)
    and worktrees via `git rev-parse --git-path hooks`.
    """
    configured = _run_git(repo_root, "config", "--get", "core.hooksPath")
    if configured.returncode == 0 and configured.stdout.strip():
        hooks = Path(configured.stdout.strip()).expanduser()
        if not hooks.is_absolute():
            hooks = (repo_root / hooks).resolve()
        return hooks

    result = _run_git(repo_root, "rev-parse", "--git-path", "hooks")
    if result.returncode != 0:
        raise HookError("Could not determine the git hooks directory.")
    hooks = Path(result.stdout.strip())
    if not hooks.is_absolute():
        hooks = (repo_root / hooks).resolve()
    return hooks


def get_install_dir(repo_root: Path) -> Path:
    return repo_root / _INSTALL_DIRNAME


