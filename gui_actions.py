class _RuleRedirectHandler(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        newurl = urllib.parse.urljoin(req.full_url, newurl)
        _validate_rule_url(newurl)
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def _validate_rule_url(url: object) -> str:
    value = str(url or "").strip()
    if not value or "\n" in value or "\r" in value or "\x00" in value:
        raise ActionError("A rule pack URL is required.")
    try:
        parsed = urllib.parse.urlsplit(value)
        port = parsed.port or (443 if parsed.scheme == "https" else 80)
    except ValueError as exc:
        raise ActionError("The rule pack URL is invalid.") from exc
    if parsed.scheme not in ("https", "http"):
        raise ActionError("Rule pack URLs must use http or https.")
    if parsed.username or parsed.password:
        raise ActionError("Rule pack URLs must not contain credentials.")
    host = (parsed.hostname or "").strip().lower()
    if not host:
        raise ActionError("The rule pack URL has no host.")
    if host in {"localhost", "localhost.localdomain"} or host.endswith(".local"):
        raise ActionError("Rule pack downloads cannot target local hosts.")
    try:
        addresses = socket.getaddrinfo(host, port, type=socket.SOCK_STREAM)
    except OSError as exc:
        raise ActionError(f"Could not resolve the rule pack host: {host}") from exc
    for entry in addresses:
        address = ipaddress.ip_address(str(entry[4][0]).split("%", 1)[0])
        mapped = getattr(address, "ipv4_mapped", None)
        candidates = [address, mapped] if mapped else [address]
        if any(
            item.is_private
            or item.is_loopback
            or item.is_link_local
            or item.is_multicast
            or item.is_reserved
            or item.is_unspecified
            for item in candidates
        ):
            raise ActionError("Rule pack downloads cannot target private or local addresses.")
    return value


def _fetch_rule_url(url: str, timeout: int = 30) -> tuple[bytes, str, str]:
    request = urllib.request.Request(
        url,
        headers={
            "User-Agent": "CommitGuard-RuleDownloader/1.0",
            "Accept": "text/plain, application/toml, application/yaml, text/yaml, */*",
            "Accept-Encoding": "identity",
        },
    )
    opener = urllib.request.build_opener(_RuleRedirectHandler())
    try:
        with opener.open(request, timeout=max(5, min(int(timeout), 60))) as response:
            final_url = _validate_rule_url(response.geturl())
            length = response.headers.get("Content-Length")
            if length:
                try:
                    if int(length) > RULE_PACK_MAX_BYTES:
                        raise ActionError("The rule pack is larger than 5 MB.")
                except ValueError:
                    pass
            data = response.read(RULE_PACK_MAX_BYTES + 1)
            content_type = response.headers.get("Content-Type", "")
    except ActionError:
        raise
    except (urllib.error.URLError, TimeoutError, OSError, ValueError) as exc:
        raise ActionError(f"Could not download the rule pack: {exc}") from exc
    if len(data) > RULE_PACK_MAX_BYTES:
        raise ActionError("The rule pack is larger than 5 MB.")
    return data, content_type, final_url


def _rule_pack_slug(name: object, url: str) -> str:
    raw = str(name or "").strip()
    if not raw:
        raw = Path(urllib.parse.urlsplit(url).path).stem
    slug = re.sub(r"[^A-Za-z0-9._-]+", "-", raw).strip(".-_").lower()
    if not slug:
        slug = "downloaded"
    if slug == "custom_rules":
        slug = "downloaded-custom-rules"
    return slug[:80]


def download_rule_pack(
    target: str | Path,
    options: dict | None = None,
    *,
    engine: str | Path | None = None,
    timeout: int = 30,
) -> dict:
    """Downloads an opt-in rule pack, validates it, and enables it immediately."""
    repo = find_repo_root(target)
    engine_path = resolve_engine(repo, engine)
    opts = options or {}
    if not isinstance(opts, dict):
        raise ActionError("Rule pack options must be an object.")
    source = str(opts.get("source") or "gitleaks").strip().lower()
    if source not in ("gitleaks", "semgrep", "custom"):
        raise ActionError(f"Unknown rule pack source: {source}")
    url = _validate_rule_url(opts.get("url") or OFFICIAL_RULE_PACKS["gitleaks"]["url"])
    rules_dir = resolve_rules_dir(repo, engine_path)
    try:
        before, _ = load_ruleset(repo, engine_path)
        before_count = len(before.rules)
    except ActionError:
        before_count = 0

    if source == "gitleaks":
        path = rules_dir / "gitleaks.toml"
        expect_yaml = False
    else:
        slug = _rule_pack_slug(opts.get("name"), url)
        subdir = "custom" if source == "custom" else "semgrep_rules"
        path = rules_dir / subdir / f"downloaded-{slug}.yaml"
        expect_yaml = True

    data, content_type, final_url = _fetch_rule_url(url, timeout=timeout)
    if not data.strip():
        raise ActionError("The downloaded rule pack is empty.")
    if b"\x00" in data:
        raise ActionError("The downloaded rule pack contains binary data.")
    if expect_yaml and not (path.suffix in (".yaml", ".yml")):
        raise ActionError("Custom rule packs must be YAML files.")

    backup: Path | None = None
    temp_path = path.with_name(f"{path.name}.tmp-{os.getpid()}")
    try:
        path.parent.mkdir(parents=True, exist_ok=True)
        if path.exists():
            backup = path.with_name(f"{path.name}.bak")
            shutil.copy2(path, backup)
        temp_path.write_bytes(data)
        os.replace(temp_path, path)
        _RULES_CACHE.clear()
        ruleset, _ = load_ruleset(repo, engine_path)
        after_count = len(ruleset.rules)
        if after_count <= before_count and source in ("semgrep", "custom"):
            raise ActionError(
                "The downloaded pack did not add any usable regex rules; "
                "the previous rule files were restored."
            )
    except ActionError:
        if backup is not None and backup.is_file():
            shutil.copy2(backup, path)
        else:
            path.unlink(missing_ok=True)
        _RULES_CACHE.clear()
        raise
    except (OSError, UnicodeDecodeError) as exc:
        if backup is not None and backup.is_file():
            shutil.copy2(backup, path)
        else:
            path.unlink(missing_ok=True)
        _RULES_CACHE.clear()
        raise ActionError(f"Could not install the rule pack: {exc}") from exc
    finally:
        temp_path.unlink(missing_ok=True)

    return {
        "ok": True,
        "source": source,
        "url": final_url,
        "path": str(path),
        "backup": str(backup) if backup else None,
        "bytes": len(data),
        "content_type": content_type,
        "rules_total": after_count,
        "rules_added": max(0, after_count - before_count),
        "skipped": len(ruleset.skipped),
        "rules_dir": str(rules_dir),
    }


