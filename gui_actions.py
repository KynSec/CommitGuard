def dependency_graph(target: str | Path, options: dict | None = None) -> dict:
    """Builds (and optionally saves) the repository dependency graph."""
    repo = find_repo_root(target)
    opts = options or {}
    fmt = str(opts.get("format") or "mermaid").strip().lower()
    if fmt not in VALID_DEP_GRAPH_FORMATS:
        raise ActionError(f"Unknown dependency graph format: {fmt}")
    max_nodes = _as_int(opts.get("max_nodes"), 250)
    if max_nodes is None or max_nodes < 1:
        raise ActionError("Graph max nodes must be a positive number.")

    from core.dep_graph import build_dependency_graph, write_dependency_graph

    try:
        graph = build_dependency_graph(repo)
        if fmt == "json":
            content = graph.to_json()
        elif fmt == "dot":
            content = graph.to_dot(max_nodes=max_nodes)
        else:
            content = graph.to_mermaid(max_nodes=max_nodes)
        saved: list[str] = []
        if _as_bool(opts.get("save")):
            try:
                report_dir = (repo / _load_config(repo).report_dir).resolve()
            except ActionError:
                report_dir = (repo / DEFAULT_REPORT_DIR).resolve()
            saved = [
                str(path)
                for path in write_dependency_graph(graph, report_dir, fmt, max_nodes=max_nodes)
            ]
    except (OSError, ValueError) as exc:
        raise ActionError(f"Could not build the dependency graph: {exc}") from exc

    return {
        "ok": True,
        "repo": str(repo),
        "format": fmt,
        "max_nodes": max_nodes,
        "content": _tail(content, 300000),
        "nodes": len(graph.nodes),
        "edges": sum(len(node.imports) for node in graph.nodes.values()),
        "external": sum(len(node.external) for node in graph.nodes.values()),
        "blast_radius": len(graph.blast_radius()),
        "saved": saved,
    }


def history_doctor(
    target: str | Path,
    limit: int = 50,
    options: dict | None = None,
    *,
    engine: str | Path | None = None,
    timeout: int = DEFAULT_TIMEOUT,
) -> dict:
    """Scans the last N commits and returns commit context for the GUI."""
    repo = find_repo_root(target)
    count = _as_int(limit, 50)
    if count is None or count < 0:
        raise ActionError("History must be zero or a positive number.")
    opts = dict(options or {})
    opts.update({"mode": "history", "history": count})
    result = run_scan(repo, opts, engine=engine, timeout=timeout)
    total_result = _git(repo, "rev-list", "--count", "HEAD")
    total = 0
    if total_result.returncode == 0:
        try:
            total = int(total_result.stdout.strip())
        except ValueError:
            total = 0
    log_limit = 50 if count == 0 else max(1, min(count, 200))
    return {
        **result,
        "history": {
            "limit": count,
            "total_commits": total,
            "commits": _git_log_entries(repo, log_limit),
        },
    }


