def list_reports(target: str | Path) -> dict:
    repo = find_repo_root(target)
    try:
        report_dir = (repo / _load_config(repo).report_dir).resolve()
    except ActionError:
        report_dir = (repo / DEFAULT_REPORT_DIR).resolve()
    files = []
    if report_dir.is_dir():
        for item in sorted(report_dir.iterdir()):
            if item.is_file():
                try:
                    stat = item.stat()
                except OSError:
                    continue
                files.append(
                    {
                        "name": item.name,
                        "path": str(item),
                        "size": stat.st_size,
                        "modified": int(stat.st_mtime),
                    }
                )
    return {"dir": str(report_dir), "files": files}


def _build_export(report: dict, fmt: str, repo: Path) -> tuple[str, str, str]:
    findings = findings_from_report(report)
    threshold = str(report.get("block_threshold") or "high")
    if fmt == "json":
        from core.reporter import build_json_report

        return (
            build_json_report(findings, threshold),
            "application/json",
            "report.json",
        )
    if fmt == "markdown":
        from core.reporter import build_markdown_report

        return (
            build_markdown_report(findings, threshold),
            "text/markdown",
            "report.md",
        )
    if fmt == "sarif":
        from core.reporter import build_sarif_report

        return (
            build_sarif_report(findings, threshold),
            "application/sarif+json",
            "report.sarif",
        )
    if fmt == "junit":
        from core.reporter import build_junit_report

        return (
            build_junit_report(findings, threshold),
            "application/xml",
            "report.junit.xml",
        )
    if fmt == "gitlab":
        from core.reporter import build_gitlab_report

        return (
            build_gitlab_report(findings, threshold),
            "application/json",
            "report.gitlab.json",
        )
    if fmt == "checkstyle":
        from core.reporter import build_checkstyle_report

        return (
            build_checkstyle_report(findings, threshold),
            "application/xml",
            "report.checkstyle.xml",
        )
    if fmt == "html":
        from core.trends import HISTORY_FILENAME, build_html_report, load_history

        try:
            report_dir = (repo / _load_config(repo).report_dir).resolve()
        except ActionError:
            report_dir = repo / DEFAULT_REPORT_DIR
        history = load_history(report_dir / HISTORY_FILENAME)
        return (
            build_html_report(
                findings,
                threshold,
                history=history,
                show_secrets=bool(report.get("redacted") is False),
                truncated=bool(report.get("truncated")),
            ),
            "text/html",
            "report.html",
        )
    raise ActionError(f"Unsupported report format: {fmt}")


def export_report(
    target: str | Path,
    report: dict,
    fmt: str,
    *,
    save: bool = False,
) -> dict:
    repo = find_repo_root(target)
    fmt = (fmt or "").lower()
    if fmt not in REPORT_FORMATS:
        raise ActionError(f"Unsupported report format: {fmt}")
    content, mimetype, filename = _build_export(report, fmt, repo)
    result = {
        "format": fmt,
        "filename": filename,
        "mimetype": mimetype,
        "content": content,
        "saved_path": None,
    }
    if save:
        try:
            report_dir = (repo / _load_config(repo).report_dir).resolve()
        except ActionError:
            report_dir = (repo / DEFAULT_REPORT_DIR).resolve()
        try:
            report_dir.mkdir(parents=True, exist_ok=True)
            path = report_dir / filename
            path.write_text(content, encoding="utf-8")
        except OSError as exc:
            raise ActionError(f"Could not save the report: {exc}") from exc
        result["saved_path"] = str(path)
    return result
