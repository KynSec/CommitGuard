def doctor(target_path: Path) -> int:
    repo_root = find_repo_root(target_path)
    install_dir = get_install_dir(repo_root)
    hooks_dir = find_hooks_dir(repo_root)
    problems = 0

    print("\n" + "=" * 66)
    print("  COMMIT GUARD — Doctor")
    print("=" * 66)
    print(f"  Repository : {repo_root}")

    try:
        version = _run_git(repo_root, "--version")
        print(f"  git        : ✅ {version.stdout.strip()}")
    except HookError as exc:
        print(f"  git        : ❌ {exc}")
        problems += 1

    print(f"  Python     : {'✅' if sys.version_info >= (3, 11) else '❌'} {sys.version.split()[0]}")
    if sys.version_info < (3, 11):  # noqa: UP036 - real runtime guard, not typing
        print("               Commit Guard requires Python 3.11+ (for tomllib).")
        problems += 1

    try:
        import yaml  # noqa: F401
        print("  PyYAML     : ✅ installed")
    except ImportError:
        print("  PyYAML     : ❌ missing (pip install pyyaml)")
        problems += 1

    if not install_dir.exists():
        print(f"  Install    : ❌ {_INSTALL_DIRNAME}/ not found — run `install`")
        problems += 1
    else:
        print(f"  Install    : ✅ {_INSTALL_DIRNAME}/")
        try:
            from core.ast_taint import TAINT_RULES
            ruleset = _load_installed_ruleset(repo_root)
            print(f"  Rules      : ✅ {len(ruleset.rules) + len(TAINT_RULES)} active")
            if ruleset.skipped:
                print(f"               {len(ruleset.skipped)} unsupported entries skipped (AST-only semgrep rules are expected)")
        except (RuleLoadError, OSError, ImportError) as exc:
            print(f"  Rules      : ❌ {exc}")
            problems += 1

    hook_path = hooks_dir / _HOOK_NAME
    if hook_path.exists():
        executable = bool(hook_path.stat().st_mode & stat.S_IXUSR)
        print(f"  Hook       : {'✅' if executable else '⚠️'} {hook_path} (executable={executable})")
        if not executable:
            problems += 1
    elif (repo_root / ".pre-commit-config.yaml").is_file():
        print("  Hook       : — native hook not installed; pre-commit framework config found")
    else:
        print("  Hook       : ❌ pre-commit hook not installed")
        problems += 1

    pre_push_path = hooks_dir / _PRE_PUSH_HOOK_NAME
    if pre_push_path.exists():
        executable = bool(pre_push_path.stat().st_mode & stat.S_IXUSR)
        print(
            f"  Push hook  : {'✅' if executable else '⚠️'} "
            f"{pre_push_path} (executable={executable})"
        )
        if not executable:
            problems += 1

    try:
        from core.config import ConfigError, load_config
        load_config(repo_root)
        print("  Config     : ✅ parsed (or defaults)")
    except (ConfigError, OSError, ImportError) as exc:
        print(f"  Config     : ❌ {exc}")
        problems += 1

    print("-" * 66)
    if problems:
        print(f"  RESULT: ❌ {problems} problem(s) found")
    else:
        print("  RESULT: ✅ healthy")
    print("=" * 66 + "\n")
    return 2 if problems else 0


def init_config(target_path: Path, force: bool = False) -> int:
    repo_root = find_repo_root(target_path)
    from core.config import default_config_text

    path = repo_root / ".commit_guard.toml"
    if path.exists() and not force:
        print(f"  [init] {path} already exists (use --force to overwrite).")
        return 0
    try:
        path.write_text(default_config_text(), encoding="utf-8")
    except OSError as exc:
        print(f"  [init] ERROR: could not write {path}: {exc}", file=sys.stderr)
        return 2
    print(f"  [init] Wrote {path}")
    return 0


def run_manual_scan(
    target_path: Path,
    *,
    threshold: str | None = None,
    quiet: bool = False,
    fmt: str | None = None,
    show_secrets: bool = False,
    diff_revision: str | None = None,
    use_baseline: bool = True,
    config_file: Path | None = None,
    report_path: Path | None = None,
    verbose_rules: bool = False,
    use_cache: bool = True,
    github_annotations: bool = False,
    soft_fail: bool = False,
    history: int | None = None,
    scan_all: bool = False,
    pre_push: bool = False,
    update_baseline: bool = False,
    fail_on: str | None = None,
    baseline_owner: str | None = None,
    baseline_expiry: str | None = None,
    audit_suppressions: bool = False,
    strict: bool = False,
    no_placeholder_filter: bool = False,
    use_policy: bool = False,
    policy_path: Path | None = None,
    policy_profile: str | None = None,
) -> int:
    repo_root = find_repo_root(target_path)
    main_py = get_install_dir(repo_root) / "main.py"
    if not main_py.is_file():
        main_py = _TOOLKIT_DIR / "main.py"

    if not main_py.is_file():
        print(
            "[commit-guard] ERROR: Commit Guard scan engine is missing. "
            "Reinstall the package or run `install`.",
            file=sys.stderr,
        )
        return 2

    command = [sys.executable, str(main_py), "--repo", str(repo_root)]
    if threshold:
        command.extend(["--threshold", threshold])
    if quiet:
        command.append("--quiet")
    if fmt:
        command.extend(["--format", fmt])
    if show_secrets:
        command.append("--show-secrets")
    if diff_revision:
        command.extend(["--diff", diff_revision])
    if not use_baseline:
        command.append("--no-baseline")
    if use_policy:
        command.append("--gate")
    if policy_path:
        command.extend(["--policy", str(policy_path)])
    if policy_profile:
        command.extend(["--policy-profile", policy_profile])
    if config_file:
        command.extend(["--config", str(config_file)])
    if report_path:
        command.extend(["--report-path", str(report_path)])
    if verbose_rules:
        command.append("--verbose-rules")
    if not use_cache:
        command.append("--no-cache")
    if github_annotations:
        command.append("--github-annotations")
    if soft_fail:
        command.append("--soft-fail")
    if history is not None:
        command.extend(["--history", str(history)])
    if scan_all:
        command.append("--all")
    if pre_push:
        command.append("--pre-push")
    if update_baseline:
        command.append("--update-baseline")
    if fail_on:
        command.extend(["--fail-on", fail_on])
    if baseline_owner:
        command.extend(["--baseline-owner", baseline_owner])
    if baseline_expiry:
        command.extend(["--baseline-expiry", baseline_expiry])
    if audit_suppressions:
        command.append("--audit-suppressions")
    if strict:
        command.append("--strict")
    if no_placeholder_filter:
        command.append("--no-placeholder-filter")

    result = subprocess.run(command, cwd=str(repo_root), check=False)
    return result.returncode


