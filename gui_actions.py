#!/usr/bin/env python3
"""
gui_actions.py — orchestration and bridge helpers for the Commit Guard GUI.

The GUI never re-implements scanning. It shells out to the same ``main.py``
and ``install_hook.py`` used by hooks and CI, and reuses ``core`` helpers for
read-only/structured operations (rule metadata, fix previews, report exports,
baseline editing, config validation).

This module deliberately imports ``core`` lazily so the HTTP server can still
start and run scans even if PyYAML is missing.
"""

