def findings_from_report(report: dict) -> list:
    from core.scanner import Finding

    findings = []
    for item in report.get("findings", []):
        findings.append(
            Finding(
                file=str(item.get("file", "")),
                line_number=int(item.get("line") or 0),
                rule_id=str(item.get("rule_id", "")),
                description=str(item.get("description", "")),
                severity=str(item.get("severity", "info")),
                source=str(item.get("source", "")),
                flagged_code=str(item.get("flagged_code", "")),
                redacted_code=str(item.get("flagged_code", "")),
                fingerprint=str(item.get("fingerprint", "")),
                tags=tuple(item.get("tags") or ()),
                cwe=item.get("cwe"),
                blocking=bool(item.get("blocking", True)),
                baseline_state=str(item.get("baseline_state", "new")),
                fixed_versions=tuple(item.get("fixed_versions") or ()),
                aliases=tuple(item.get("aliases") or ()),
                advisory_url=item.get("advisory_url"),
            )
        )
    return findings


def list_rules(target: str | Path, engine: str | Path | None = None) -> dict:
    repo = find_repo_root(target)
    engine_path = resolve_engine(repo, engine)
    ruleset, rules_dir = load_ruleset(repo, engine_path)
    from core.ast_taint import TAINT_RULES

    items = []
    for rule in ruleset.rules:
        items.append(
            {
                "rule_id": rule.rule_id,
                "description": rule.description,
                "severity": rule.severity,
                "source": rule.source,
                "tags": list(rule.tags),
                "cwe": rule.cwe,
                "is_secret": rule.is_secret,
                "fixable": bool(rule.fix_pattern is not None and rule.fix_replacement is not None),
                "languages": list(rule.languages),
            }
        )
    for rule_id, details in TAINT_RULES.items():
        items.append(
            {
                "rule_id": rule_id,
                "description": details["description"],
                "severity": details["severity"],
                "source": "python_ast",
                "tags": list(details.get("tags", ())),
                "cwe": details.get("cwe"),
                "is_secret": False,
                "fixable": False,
                "languages": [".py", ".pyi"],
            }
        )
    items.sort(key=lambda item: (item["source"], item["rule_id"]))
    return {
        "rules": items,
        "total": len(items),
        "rules_dir": str(rules_dir),
        "skipped": len(ruleset.skipped),
    }


def explain_rule(target: str | Path, rule_id: str, engine: str | Path | None = None) -> dict:
    repo = find_repo_root(target)
    engine_path = resolve_engine(repo, engine)
    ruleset, _ = load_ruleset(repo, engine_path)
    for rule in ruleset.rules:
        if rule.rule_id == rule_id:
            return {
                "rule_id": rule.rule_id,
                "description": rule.description,
                "severity": rule.severity,
                "source": rule.source,
                "pattern": rule.pattern.pattern,
                "languages": list(rule.languages),
                "paths": [regex.pattern for regex in rule.path_regexes],
                "tags": list(rule.tags),
                "cwe": rule.cwe,
                "is_secret": rule.is_secret,
                "entropy": rule.entropy,
                "keywords": list(rule.keywords),
                "fixable": bool(rule.fix_pattern is not None and rule.fix_replacement is not None),
                "fix_pattern": rule.fix_pattern.pattern if rule.fix_pattern else None,
                "fix_replacement": rule.fix_replacement,
            }
    from core.ast_taint import TAINT_RULES

    details = TAINT_RULES.get(rule_id)
    if details:
        return {
            "rule_id": rule_id,
            "description": details["description"],
            "severity": details["severity"],
            "source": "python_ast",
            "pattern": None,
            "languages": [".py", ".pyi"],
            "paths": [],
            "tags": list(details.get("tags", ())),
            "cwe": details.get("cwe"),
            "is_secret": False,
            "entropy": None,
            "keywords": [],
            "fixable": False,
            "fix_pattern": None,
            "fix_replacement": None,
        }
    raise ActionError(f"No active rule with id '{rule_id}'.", status=404)


