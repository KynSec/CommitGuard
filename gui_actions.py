def _baseline_path(repo: Path) -> Path:
    return repo / BASELINE_FILENAME


def baseline_entries(target: str | Path) -> dict:
    repo = find_repo_root(target)
    from core.suppressions import parse_baseline_entries

    entries = parse_baseline_entries(_baseline_path(repo))
    return {
        "path": str(_baseline_path(repo)),
        "exists": _baseline_path(repo).is_file(),
        "entries": [
            {
                "line": entry.line_number,
                "kind": entry.kind,
                "value": entry.value,
                "owner": entry.owner,
                "expiry": entry.expiry.isoformat() if entry.expiry else None,
                "raw": entry.raw,
            }
            for entry in entries
        ],
    }


def suppress_findings(
    target: str | Path,
    fingerprints: list[str],
    *,
    owner: str | None = None,
    expiry: str | None = None,
) -> dict:
    repo = find_repo_root(target)
    values = [str(value) for value in fingerprints if str(value).strip()]
    if not values:
        raise ActionError("No fingerprints were selected.")
    if expiry:
        try:
            date.fromisoformat(expiry)
        except ValueError as exc:
            raise ActionError("Expiry must use YYYY-MM-DD.") from exc
    from core.suppressions import add_fingerprints

    try:
        added = add_fingerprints(
            _baseline_path(repo),
            values,
            owner=owner or None,
            expiry=expiry or None,
        )
    except OSError as exc:
        raise ActionError(f"Could not update the baseline: {exc}") from exc
    return {"added": added, "path": str(_baseline_path(repo))}


def update_baseline(
    target: str | Path,
    report: dict,
    *,
    owner: str | None = None,
    expiry: str | None = None,
) -> dict:
    fingerprints = [
        str(item.get("fingerprint", ""))
        for item in report.get("findings", [])
        if item.get("fingerprint")
    ]
    if not fingerprints:
        return {"added": 0, "path": str(_baseline_path(find_repo_root(target)))}
    return suppress_findings(target, fingerprints, owner=owner, expiry=expiry)


def audit_suppressions(
    target: str | Path,
    report: dict | None = None,
    *,
    engine: str | Path | None = None,
) -> dict:
    repo = find_repo_root(target)
    engine_path = resolve_engine(repo, engine)
    from core.suppressions import audit_entries, parse_baseline_entries

    entries = parse_baseline_entries(_baseline_path(repo))
    try:
        ruleset, _ = load_ruleset(repo, engine_path)
        known = {rule.rule_id for rule in ruleset.rules}
    except ActionError:
        known = set()
    from core.ast_taint import TAINT_RULES

    known |= set(TAINT_RULES)
    tracked = _git(repo, "ls-files")
    tracked_paths = set(tracked.stdout.splitlines()) if tracked.returncode == 0 else set()
    current = None
    if report is not None:
        current = {
            str(item.get("fingerprint", ""))
            for item in report.get("findings", [])
            if item.get("fingerprint")
        }
    issues = audit_entries(
        entries,
        known_rule_ids=known,
        tracked_paths=tracked_paths,
        current_fingerprints=current,
    )
    return {
        "entries": len(entries),
        "issues": issues,
        "clean": not issues,
    }


