def _git(repo: Path, *args: str) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            ["git", *args],
            cwd=str(repo),
            capture_output=True,
            text=True,
            check=False,
        )
    except FileNotFoundError as exc:
        raise ActionError("git was not found on PATH.", status=500) from exc


def find_repo_root(target: str | Path) -> Path:
    path = Path(target).expanduser()
    if not path.exists():
        raise ActionError(f"Path does not exist: {path}")
    if not path.is_dir():
        raise ActionError(f"Path is not a directory: {path}")
    result = _git(path, "rev-parse", "--show-toplevel")
    if result.returncode != 0:
        raise ActionError(f"Not inside a git repository: {path}")
    return Path(result.stdout.strip()).resolve()


def parse_github_slug(remote: str | None) -> str | None:
    """Extracts owner/repo from common GitHub remote URL forms."""
    if not remote:
        return None
    value = remote.strip()
    if not value:
        return None
    value = value.removesuffix(".git")
    patterns = (
        r"github\.com[:/]+([^/]+)/([^/]+)$",
        r"^([^/]+)/([^/]+)$",
    )
    for pattern in patterns:
        match = re.search(pattern, value)
        if match:
            return f"{match.group(1)}/{match.group(2)}"
    return None


def _hooks_dir(repo: Path) -> Path:
    configured = _git(repo, "config", "--get", "core.hooksPath")
    if configured.returncode == 0 and configured.stdout.strip():
        hooks = Path(configured.stdout.strip()).expanduser()
        if not hooks.is_absolute():
            hooks = (repo / hooks).resolve()
        return hooks
    result = _git(repo, "rev-parse", "--git-path", "hooks")
    hooks = Path(result.stdout.strip()) if result.returncode == 0 else Path(".git/hooks")
    if not hooks.is_absolute():
        hooks = (repo / hooks).resolve()
    return hooks


def _hook_state(repo: Path) -> str:
    hooks = _hooks_dir(repo)
    active = hooks / "pre-commit"
    disabled = hooks / "pre-commit.disabled"
    for path, label in ((active, "active"), (disabled, "disabled")):
        try:
            if HOOK_MARKER in path.read_text(encoding="utf-8", errors="replace"):
                return label
        except OSError:
            continue
    return "misc" if active.exists() else "missing"


def resolve_engine(repo: Path, engine: str | Path | None = None) -> Path:
    if engine:
        path = Path(engine).expanduser().resolve()
        if not path.is_file():
            raise ActionError(f"Engine not found: {path}", status=500)
        return path
    installed = repo / INSTALL_DIRNAME / "main.py"
    if installed.is_file():
        return installed
    sibling = TOOLKIT_DIR / "main.py"
    if sibling.is_file():
        return sibling
    raise ActionError("Could not locate main.py for the scan engine.", status=500)


def resolve_install_hook(repo: Path) -> Path:
    installed = repo / INSTALL_DIRNAME / "install_hook.py"
    if installed.is_file():
        return installed
    sibling = TOOLKIT_DIR / "install_hook.py"
    if sibling.is_file():
        return sibling
    raise ActionError("Could not locate install_hook.py for maintenance actions.", status=500)


def _load_config(repo: Path):
    from core.config import load_config

    try:
        return load_config(repo)
    except Exception as exc:  # ConfigError or import failure
        raise ActionError(f"Could not load configuration: {exc}") from exc


def resolve_rules_dir(repo: Path, engine: Path) -> Path:
    try:
        config = _load_config(repo)
    except ActionError:
        config = None
    if config is not None and config.rules_dir is not None:
        path = config.rules_dir.expanduser()
        if not path.is_absolute():
            path = (repo / path).resolve()
        return path
    installed = repo / INSTALL_DIRNAME / "rules"
    if installed.is_dir():
        return installed
    return engine.parent / "rules"


def _rules_signature(path: Path) -> tuple:
    entries = []
    if path.is_dir():
        for item in sorted(path.rglob("*")):
            if item.is_file() and item.suffix.lower() in (".toml", ".yaml", ".yml", ".conf"):
                try:
                    stat = item.stat()
                except OSError:
                    continue
                entries.append((str(item), stat.st_size, stat.st_mtime_ns))
    return (str(path), tuple(entries))


_RULES_CACHE: dict[tuple, object] = {}


def load_ruleset(repo: Path, engine: Path):
    """Loads and caches the applicable ruleset for a repository."""
    from core.rule_loader import RuleLoadError
    from core.rule_loader import load_ruleset as _load

    rules_dir = resolve_rules_dir(repo, engine)
    signature = _rules_signature(rules_dir)
    cached = _RULES_CACHE.get(signature)
    if cached is not None:
        return cached, rules_dir
    try:
        ruleset = _load(rules_dir, warn=False, use_cache=True)
    except (RuleLoadError, OSError) as exc:
        raise ActionError(f"Could not load rules from {rules_dir}: {exc}") from exc
    _RULES_CACHE.clear()
    _RULES_CACHE[signature] = ruleset
    return ruleset, rules_dir


