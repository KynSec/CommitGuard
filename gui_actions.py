def git_create_branch(
    target: str | Path,
    name: str,
    *,
    start_point: str = "",
    checkout: bool = True,
) -> dict:
    repo = find_repo_root(target)
    branch_name = _validate_branch_name(repo, name)
    if _git(repo, "show-ref", "--verify", "--quiet", f"refs/heads/{branch_name}").returncode == 0:
        raise ActionError(f"Branch already exists: {branch_name}")
    start = str(start_point or "").strip()
    if start.startswith("-") or "\n" in start or "\r" in start or "\x00" in start:
        raise ActionError("Invalid branch start point.")
    if checkout:
        args = ["switch", "-c", branch_name]
    else:
        args = ["branch", branch_name]
    if start:
        args.append(start)
    result = _git(repo, *args)
    if result.returncode != 0:
        raise ActionError(
            _redact_git_text((result.stderr or result.stdout or "Could not create branch.").strip())
        )
    return {
        "ok": True,
        "branch": branch_name,
        "checked_out": checkout,
        "output": _redact_git_text(_tail(f"{result.stdout}{result.stderr}")),
        "status": git_status(repo),
    }


