def _write_profile_config(repo_root: Path, profile: str, force: bool = False) -> None:
    from core.config import ConfigError, default_config_text, profile_defaults

    try:
        values = profile_defaults(profile)
    except ConfigError as exc:
        raise HookError(str(exc)) from exc
    path = repo_root / ".commit_guard.toml"
    if path.exists() and not force:
        print(
            f"  [install] Keeping existing {path.name}; "
            f"profile '{profile}' was not written (use --force to replace)."
        )
        return
    text = default_config_text()
    text = text.replace(
        'profile = "balanced"', f'profile = "{profile}"'
    )
    text = text.replace(
        'threshold = "high"', f'threshold = "{values["threshold"]}"'
    )
    if values.get("soft_fail"):
        text = text.replace("# soft_fail = false", "soft_fail = true")
    header = (
        f"# Generated with `install --profile {profile}`.\n"
        f"# Edit freely; run `install --profile {profile} --force` to reset.\n\n"
    )
    path.write_text(header + text, encoding="utf-8")
    print(f"  [install] Wrote {profile} profile to {path.name}")


def install(
    target_path: Path,
    source_root: Path | None = None,
    force: bool = False,
    update_gitignore_flag: bool = True,
    pre_push: bool = False,
    profile: str | None = None,
    pre_commit_hook: bool = True,
) -> Path:
    repo_root = find_repo_root(target_path)
    source_root = source_root or _TOOLKIT_DIR

    print(f"[commit-guard] Installing into: {repo_root}")
    install_dir = copy_toolkit(repo_root, source_root, force=force)
    write_wrapper_scripts(repo_root)
    if pre_commit_hook:
        write_hook(repo_root, install_dir)
    if pre_push:
        write_pre_push_hook(repo_root, install_dir)
    if profile:
        _write_profile_config(repo_root, profile, force=force)
    if update_gitignore_flag:
        update_gitignore(repo_root)

    print(
        "\n✅ Commit Guard is installed and self-contained in this repo.\n"
        + (
            "   Scans now run automatically on every `git commit`.\n"
            if pre_commit_hook
            else "   No native hook was installed (use the pre-commit framework manifest).\n"
        )
        + ("   The pre-push hook also audits every pushed commit.\n" if pre_push else "")
        + f"   Manual commands: ./{_WRAPPER_SH_NAME} scan | status | doctor | disable | enable | uninstall\n"
        f"   Configuration:   {repo_root / '.commit_guard.toml'} (run `./{_WRAPPER_SH_NAME} init`)\n"
    )
    return install_dir


def update(
    target_path: Path,
    source_root: Path | None = None,
    force: bool = False,
) -> Path:
    repo_root = find_repo_root(target_path)
    source_root = source_root or _TOOLKIT_DIR
    if not get_install_dir(repo_root).exists():
        raise HookError("Commit Guard isn't installed here. Run `install` first.")
    print(f"[commit-guard] Updating: {repo_root}")
    hooks_dir = find_hooks_dir(repo_root)
    has_pre_commit = _has_managed_hook(
        hooks_dir, _HOOK_NAME, _DISABLED_HOOK_NAME
    )
    has_pre_push = _has_managed_hook(
        hooks_dir, _PRE_PUSH_HOOK_NAME, _DISABLED_PRE_PUSH_HOOK_NAME
    )
    pre_commit_disabled = _hook_has_marker(hooks_dir / _DISABLED_HOOK_NAME)
    pre_push_disabled = _hook_has_marker(hooks_dir / _DISABLED_PRE_PUSH_HOOK_NAME)
    install_dir = copy_toolkit(repo_root, source_root, force=force)
    write_wrapper_scripts(repo_root)
    if has_pre_commit:
        write_hook(repo_root, install_dir)
        if pre_commit_disabled:
            (hooks_dir / _HOOK_NAME).replace(hooks_dir / _DISABLED_HOOK_NAME)
    if has_pre_push:
        write_pre_push_hook(repo_root, install_dir)
        if pre_push_disabled:
            (hooks_dir / _PRE_PUSH_HOOK_NAME).replace(
                hooks_dir / _DISABLED_PRE_PUSH_HOOK_NAME
            )
    update_gitignore(repo_root)
    print("\n✅ Commit Guard engine updated.\n")
    return install_dir


def uninstall(target_path: Path) -> bool:
    repo_root = find_repo_root(target_path)
    hooks_dir = find_hooks_dir(repo_root)
    hook_path = hooks_dir / _HOOK_NAME
    disabled_path = hooks_dir / _DISABLED_HOOK_NAME
    backup_path = hooks_dir / _BACKUP_HOOK_NAME
    pre_push_path = hooks_dir / _PRE_PUSH_HOOK_NAME
    disabled_pre_push_path = hooks_dir / _DISABLED_PRE_PUSH_HOOK_NAME
    backup_pre_push_path = hooks_dir / _BACKUP_PRE_PUSH_HOOK_NAME
    install_dir = get_install_dir(repo_root)

    removed_anything = False

    for name, path in (("pre-commit", hook_path), ("pre-push", pre_push_path)):
        if not path.exists():
            continue
        try:
            content = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            content = ""
        if _HOOK_MARKER in content:
            path.unlink()
            print(f"  [uninstall] Removed active {name} hook.")
            removed_anything = True
        else:
            print(
                f"  [uninstall] Left the {name} hook untouched "
                "(it was not installed by Commit Guard)."
            )

    for name, path in (
        ("pre-commit", disabled_path),
        ("pre-push", disabled_pre_push_path),
    ):
        if not path.exists():
            continue
        try:
            content = path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            content = ""
        if _HOOK_MARKER in content:
            path.unlink()
            print(f"  [uninstall] Removed disabled {name} hook.")
            removed_anything = True

    for name, backup, target in (
        ("pre-commit", backup_path, hook_path),
        ("pre-push", backup_pre_push_path, pre_push_path),
    ):
        if backup.exists():
            if not target.exists():
                backup.replace(target)
                print(f"  [uninstall] Restored the {name} hook that was here before Commit Guard.")
                removed_anything = True
            else:
                print(
                    f"  [uninstall] Kept {backup.name}; a different "
                    f"{name} hook is now active."
                )

    if remove_wrapper_scripts(repo_root):
        print(f"  [uninstall] Removed ./{_WRAPPER_SH_NAME} and ./{_WRAPPER_BAT_NAME}")
        removed_anything = True

    if install_dir.exists():
        shutil.rmtree(install_dir)
        print(f"  [uninstall] Removed {install_dir}")
        removed_anything = True

    if not removed_anything:
        print("  [uninstall] Nothing to remove — Commit Guard isn't installed here.")
        return False

    print(
        "  [uninstall] Commit Guard fully removed from this repository.\n"
        "  [uninstall] Kept your files: .commit_guard.toml, .commit_guard_ignore, "
        "commit_guard_reports/."
    )
    return True


def disable(target_path: Path) -> bool:
    repo_root = find_repo_root(target_path)
    hooks_dir = find_hooks_dir(repo_root)
    changed = False
    found = False
    for name, hook_name, disabled_name in (
        ("pre-commit", _HOOK_NAME, _DISABLED_HOOK_NAME),
        ("pre-push", _PRE_PUSH_HOOK_NAME, _DISABLED_PRE_PUSH_HOOK_NAME),
    ):
        hook_path = hooks_dir / hook_name
        disabled_path = hooks_dir / disabled_name
        if hook_path.exists():
            try:
                content = hook_path.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                content = ""
            if _HOOK_MARKER not in content:
                print(f"  [disable] {name} hook is not managed by Commit Guard; left untouched.")
                continue
            found = True
            hook_path.replace(disabled_path)
            print(f"  [disable] {name} hook turned OFF. Manual scans still work.")
            changed = True
        elif disabled_path.exists():
            found = True
            print(f"  [disable] {name} hook is already disabled.")
    if not found:
        print("  [disable] No active hook found — nothing to disable. Run `install` first.")
        return False
    return changed or found


def enable(target_path: Path) -> bool:
    repo_root = find_repo_root(target_path)
    hooks_dir = find_hooks_dir(repo_root)
    changed = False
    found = False
    for name, hook_name, disabled_name in (
        ("pre-commit", _HOOK_NAME, _DISABLED_HOOK_NAME),
        ("pre-push", _PRE_PUSH_HOOK_NAME, _DISABLED_PRE_PUSH_HOOK_NAME),
    ):
        hook_path = hooks_dir / hook_name
        disabled_path = hooks_dir / disabled_name
        if hook_path.exists():
            try:
                content = hook_path.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                content = ""
            if _HOOK_MARKER in content:
                found = True
                print(f"  [enable] {name} hook is already enabled.")
        elif disabled_path.exists():
            try:
                content = disabled_path.read_text(encoding="utf-8", errors="ignore")
            except OSError:
                content = ""
            if _HOOK_MARKER not in content:
                print(f"  [enable] {name} disabled hook is not managed by Commit Guard; left untouched.")
                continue
            found = True
            disabled_path.replace(hook_path)
            hook_path.chmod(
                hook_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH
            )
            print(f"  [enable] {name} hook turned back ON.")
            changed = True
    if not found:
        print("  [enable] No installed hook found. Run `install` first.")
        return False
    return changed or found


