def update_gitignore(repo_root: Path) -> bool:
    gitignore_path = repo_root / ".gitignore"
    existing_content = ""
    if gitignore_path.exists():
        existing_content = gitignore_path.read_text(encoding="utf-8", errors="replace")

    existing_lines = {line.strip() for line in existing_content.splitlines()}
    missing = [
        entry
        for entry in GITIGNORE_ENTRIES
        if not entry.startswith("#") and entry.strip() not in existing_lines
    ]
    if not missing:
        return False

    with open(gitignore_path, "a", encoding="utf-8") as handle:
        if existing_content and not existing_content.endswith("\n"):
            handle.write("\n")
        if existing_content and not existing_content.endswith("\n\n"):
            handle.write("\n")
        handle.write("# Commit Guard (local security scanner) — safe to delete anytime\n")
        handle.writelines(entry + "\n" for entry in missing)

    print(f"  [install] Added Commit Guard entries to {gitignore_path.name}")
    return True


