def _as_bool(value: object, default: bool = False) -> bool:
    if value is None:
        return default
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() in ("1", "true", "yes", "on")


def _as_int(value: object, default: int | None = None) -> int | None:
    if value is None or value == "":
        return default
    try:
        return int(value)
    except (TypeError, ValueError) as exc:
        raise ActionError(f"Expected an integer, got: {value!r}") from exc


def build_scan_command(
    engine: Path,
    repo: Path,
    report_path: Path,
    options: dict | None = None,
) -> list[str]:
    """Builds the exact ``main.py`` argument list for a GUI scan request."""
    opts = options or {}
    mode = str(opts.get("mode") or "staged").lower()
    if mode not in VALID_MODES:
        raise ActionError(f"Unknown scan mode: {mode}")
    threshold = str(opts.get("threshold") or "high").lower()
    if threshold not in VALID_THRESHOLDS:
        raise ActionError(f"Unknown threshold: {threshold}")

    command = [
        sys.executable,
        str(engine),
        "--repo",
        str(repo),
        "--format",
        "json",
        "--report-path",
        str(report_path),
        "--threshold",
        threshold,
        "--quiet",
    ]
    if mode == "all":
        command.append("--all")
    elif mode == "history":
        history = _as_int(opts.get("history"), 0)
        if history is None or history < 0:
            raise ActionError("History must be zero or a positive number.")
        command.extend(["--history", str(history)])
    elif mode == "diff":
        revision = str(opts.get("diff") or "").strip()
        if not revision:
            raise ActionError("A revision range is required for diff mode.")
        command.extend(["--diff", revision])

    if _as_bool(opts.get("show_secrets")):
        command.append("--show-secrets")
    if _as_bool(opts.get("no_baseline")):
        command.append("--no-baseline")
    if _as_bool(opts.get("no_cache")):
        command.append("--no-cache")
    if _as_bool(opts.get("no_placeholder_filter")):
        command.append("--no-placeholder-filter")
    fail_on = str(opts.get("fail_on") or "").strip().lower()
    if fail_on in ("all", "new"):
        command.extend(["--fail-on", fail_on])
    if _as_bool(opts.get("dep_graph")):
        command.append("--dep-graph")
        graph_format = str(opts.get("dep_graph_format") or "mermaid").lower()
        if graph_format not in VALID_DEP_GRAPH_FORMATS:
            raise ActionError(f"Unknown dependency graph format: {graph_format}")
        command.extend(["--dep-graph-format", graph_format])
        max_nodes = _as_int(opts.get("dep_graph_max_nodes"), 250)
        if max_nodes is not None:
            command.extend(["--dep-graph-max-nodes", str(max_nodes)])
    if _as_bool(opts.get("sca")):
        command.append("--sca")
        if _as_bool(opts.get("sca_online")):
            command.append("--sca-online")
        snapshot = str(opts.get("sca_snapshot") or "").strip()
        if snapshot:
            command.extend(["--sca-snapshot", snapshot])
        timeout = _as_int(opts.get("sca_timeout"), 20)
        if timeout is not None:
            if timeout < 1:
                raise ActionError("SCA timeout must be a positive number.")
            command.extend(["--sca-timeout", str(timeout)])
    return command


def _run(
    command: list[str],
    *,
    cwd: Path,
    env: dict | None = None,
    timeout: int = DEFAULT_TIMEOUT,
) -> subprocess.CompletedProcess[str]:
    try:
        return subprocess.run(
            command,
            cwd=str(cwd),
            capture_output=True,
            text=True,
            timeout=max(1, int(timeout)),
            check=False,
            env=env,
        )
    except subprocess.TimeoutExpired as exc:
        raise ActionError(
            f"The operation timed out after {timeout}s.",
            detail={"stdout": _tail(exc.stdout), "stderr": _tail(exc.stderr)},
            status=504,
        ) from exc
    except OSError as exc:
        raise ActionError(f"Could not start the Commit Guard engine: {exc}", status=500) from exc


def _tail(value: object, limit: int = 40000) -> str:
    if value is None:
        return ""
    if isinstance(value, bytes):
        value = value.decode("utf-8", "replace")
    text = str(value)
    return text if len(text) <= limit else text[-limit:]


def _read_report(path: Path) -> dict:
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        raise ActionError(f"Could not read the scan report: {exc}", status=500) from exc
    if not isinstance(payload, dict) or not isinstance(payload.get("findings"), list):
        raise ActionError("The scan report has an unexpected format.", status=500)
    return payload


def annotate_report(repo: Path, engine: Path, report: dict) -> dict:
    """Adds rule metadata (fixable/secret) needed by the UI."""
    try:
        ruleset, _ = load_ruleset(repo, engine)
    except ActionError:
        for finding in report.get("findings", []):
            finding.setdefault("fixable", False)
            finding.setdefault("is_secret", False)
        report["fixable"] = 0
        return report
    rules = {rule.rule_id: rule for rule in ruleset.rules}
    fixable = 0
    for finding in report.get("findings", []):
        rule = rules.get(finding.get("rule_id"))
        can_fix = bool(
            rule
            and rule.fix_pattern is not None
            and rule.fix_replacement is not None
            and not rule.is_secret
        )
        finding["fixable"] = can_fix
        finding["is_secret"] = bool(rule.is_secret) if rule else False
        if can_fix:
            fixable += 1
    report["fixable"] = fixable
    return report


def run_scan(
    target: str | Path,
    options: dict | None = None,
    *,
    engine: str | Path | None = None,
    timeout: int = DEFAULT_TIMEOUT,
) -> dict:
    repo = find_repo_root(target)
    engine_path = resolve_engine(repo, engine)
    opts = options or {}
    started = time.perf_counter()
    with tempfile.TemporaryDirectory(prefix="commitguard-gui-") as temp:
        report_path = Path(temp) / "report.json"
        command = build_scan_command(engine_path, repo, report_path, opts)
        result = _run(command, cwd=repo, timeout=timeout)
        duration_ms = int((time.perf_counter() - started) * 1000)
        detail = {
            "exit_code": result.returncode,
            "stdout": _tail(result.stdout),
            "stderr": _tail(result.stderr),
            "command": command,
            "duration_ms": duration_ms,
        }
        if result.returncode not in (0, 1) or not report_path.is_file():
            message = (result.stderr or result.stdout or "The scan failed.").strip()
            raise ActionError(message.splitlines()[-1] if message else "The scan failed.", detail=detail)
        report = _read_report(report_path)
    report = annotate_report(repo, engine_path, report)
    return {
        "ok": True,
        "repo": str(repo),
        "engine": str(engine_path),
        **detail,
        "report": report,
    }


