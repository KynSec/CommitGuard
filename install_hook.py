def _shell_python_selector() -> str:
    """Returns shell snippet that sets $PY to a runnable Python interpreter."""
    embedded = sys.executable.replace("\\", "/")
    return (
        'if [ -n "${COMMIT_GUARD_PYTHON:-}" ]; then\n'
        '    PY="$COMMIT_GUARD_PYTHON"\n'
        f'elif [ -x "{embedded}" ]; then\n'
        f'    PY="{embedded}"\n'
        "elif command -v python3 >/dev/null 2>&1; then\n"
        "    PY=python3\n"
        "elif command -v python >/dev/null 2>&1; then\n"
        "    PY=python\n"
        "else\n"
        '    echo "[commit-guard] ERROR: no Python interpreter found; set COMMIT_GUARD_PYTHON." >&2\n'
        "    exit 2\n"
        "fi\n"
    )


def _render_hook_script(install_dir: Path) -> str:
    return (
        "#!/bin/sh\n"
        f"# {_HOOK_MARKER}. Manage with: ./{_WRAPPER_SH_NAME} status|disable|enable|uninstall\n"
        "# Calls the SELF-CONTAINED copy in .commit_guard/ — no external toolkit needed.\n"
        "\n"
        'REPO_DIR="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"\n'
        f'GUARD_DIR="$REPO_DIR/{_INSTALL_DIRNAME}"\n'
        f"FALLBACK_GUARD={shlex.quote(str(install_dir))}\n"
        'if [ ! -f "$GUARD_DIR/main.py" ] && [ -f "$FALLBACK_GUARD/main.py" ]; then\n'
        '    GUARD_DIR="$FALLBACK_GUARD"\n'
        "fi\n"
        'if [ ! -f "$GUARD_DIR/main.py" ]; then\n'
        '    echo "[commit-guard] WARNING: $GUARD_DIR/main.py is missing; skipping scan." >&2\n'
        "    exit 0\n"
        "fi\n"
        "\n"
        + _shell_python_selector()
        + '\nif [ -n "${COMMIT_GUARD_THRESHOLD:-}" ]; then\n'
        '    exec "$PY" "$GUARD_DIR/main.py" --repo "$REPO_DIR" --gate --threshold "$COMMIT_GUARD_THRESHOLD"\n'
        "fi\n"
        'exec "$PY" "$GUARD_DIR/main.py" --repo "$REPO_DIR" --gate\n'
    )


def _render_wrapper_sh() -> str:
    return (
        "#!/bin/sh\n"
        f"# {_HOOK_MARKER}. Safe to delete along with {_INSTALL_DIRNAME}/.\n"
        "# Examples: ./commit-guard scan | status | doctor | disable | enable | uninstall\n"
        'TOOL_DIR="$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)"\n'
        f'GUARD_DIR="$TOOL_DIR/{_INSTALL_DIRNAME}"\n'
        'if [ ! -f "$GUARD_DIR/install_hook.py" ]; then\n'
        '    echo "[commit-guard] ERROR: $GUARD_DIR/install_hook.py is missing; reinstall Commit Guard." >&2\n'
        "    exit 2\n"
        "fi\n"
        "\n"
        + _shell_python_selector()
        + '\nexec "$PY" "$GUARD_DIR/install_hook.py" "$@"\n'
    )


def _render_wrapper_bat() -> str:
    embedded = sys.executable
    return (
        "@echo off\r\n"
        "setlocal\r\n"
        f"REM {_HOOK_MARKER}. Examples: commit-guard.bat scan / status / doctor / uninstall\r\n"
        'set "GUARD_DIR=%~dp0.commit_guard"\r\n'
        'if not exist "%GUARD_DIR%\\install_hook.py" (\r\n'
        '  echo [commit-guard] ERROR: %GUARD_DIR%\\install_hook.py is missing; reinstall Commit Guard. 1>&2\r\n'
        "  exit /b 2\r\n"
        ")\r\n"
        'if defined COMMIT_GUARD_PYTHON set "PY=%COMMIT_GUARD_PYTHON%"\r\n'
        'if not defined PY if exist "' + embedded + '" set "PY=' + embedded + '"\r\n'
        "if not defined PY (\r\n"
        '  where py >nul 2>nul && set "PY=py -3"\r\n'
        ")\r\n"
        "if not defined PY set \"PY=python\"\r\n"
        '%PY% "%GUARD_DIR%\\install_hook.py" %*\r\n'
        "exit /b %ERRORLEVEL%\r\n"
    )


def _hook_has_marker(path: Path) -> bool:
    if not path.exists():
        return False
    try:
        return _HOOK_MARKER in path.read_text(encoding="utf-8", errors="ignore")
    except OSError:
        return False


def _has_managed_hook(hooks_dir: Path, active_name: str, disabled_name: str) -> bool:
    return _hook_has_marker(hooks_dir / active_name) or _hook_has_marker(
        hooks_dir / disabled_name
    )


def _rotate_backup(path: Path) -> Path:
    """Returns a free backup path, preserving any earlier backup file."""
    if not path.exists():
        return path
    for index in range(1, 1000):
        candidate = path.with_name(f"{path.name}.{index}")
        if not candidate.exists():
            return candidate
    raise HookError(f"Could not find a free backup name beside {path}.")


def write_hook(repo_root: Path, install_dir: Path) -> Path:
    hooks_dir = find_hooks_dir(repo_root)
    hooks_dir.mkdir(parents=True, exist_ok=True)

    hook_path = hooks_dir / _HOOK_NAME
    disabled_path = hooks_dir / _DISABLED_HOOK_NAME

    if disabled_path.exists():
        disabled_path.unlink()

    if hook_path.exists():
        try:
            existing = hook_path.read_text(encoding="utf-8", errors="ignore")
        except OSError:
            existing = ""
        if _HOOK_MARKER in existing:
            hook_path.unlink()  # our own hook: replace without clobbering the backup
        else:
            backup_path = _rotate_backup(hooks_dir / _BACKUP_HOOK_NAME)
            print(f"  [install] Existing pre-commit hook found — backing up to {backup_path.name}")
            hook_path.replace(backup_path)

    hook_path.write_text(_render_hook_script(install_dir), encoding="utf-8", newline="\n")
    hook_path.chmod(hook_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"  [install] Pre-commit hook installed at {hook_path}")
    return hook_path


def _render_pre_push_hook_script(install_dir: Path) -> str:
    return (
        "#!/bin/sh\n"
        f"# {_HOOK_MARKER}. Manage with: ./{_WRAPPER_SH_NAME} status|disable|enable|uninstall\n"
        "# Reads git's pre-push ref lines from stdin and audits commits being pushed.\n"
        "\n"
        'REPO_DIR="$(git rev-parse --show-toplevel 2>/dev/null || pwd)"\n'
        f'GUARD_DIR="$REPO_DIR/{_INSTALL_DIRNAME}"\n'
        f"FALLBACK_GUARD={shlex.quote(str(install_dir))}\n"
        'if [ ! -f "$GUARD_DIR/main.py" ] && [ -f "$FALLBACK_GUARD/main.py" ]; then\n'
        '    GUARD_DIR="$FALLBACK_GUARD"\n'
        "fi\n"
        'if [ ! -f "$GUARD_DIR/main.py" ]; then\n'
        '    echo "[commit-guard] WARNING: $GUARD_DIR/main.py is missing; skipping scan." >&2\n'
        "    exit 0\n"
        "fi\n"
        "\n"
        + _shell_python_selector()
        + '\nif [ -n "${COMMIT_GUARD_THRESHOLD:-}" ]; then\n'
        '    exec "$PY" "$GUARD_DIR/main.py" --repo "$REPO_DIR" --pre-push --gate --threshold "$COMMIT_GUARD_THRESHOLD"\n'
        "fi\n"
        'exec "$PY" "$GUARD_DIR/main.py" --repo "$REPO_DIR" --pre-push --gate\n'
    )


def write_pre_push_hook(repo_root: Path, install_dir: Path) -> Path:
    hooks_dir = find_hooks_dir(repo_root)
    hooks_dir.mkdir(parents=True, exist_ok=True)
    hook_path = hooks_dir / _PRE_PUSH_HOOK_NAME
    disabled_path = hooks_dir / _DISABLED_PRE_PUSH_HOOK_NAME

    if disabled_path.exists():
        disabled_path.unlink()
    if hook_path.exists():
        if _hook_has_marker(hook_path):
            hook_path.unlink()
        else:
            backup_path = _rotate_backup(hooks_dir / _BACKUP_PRE_PUSH_HOOK_NAME)
            print(f"  [install] Existing pre-push hook found — backing up to {backup_path.name}")
            hook_path.replace(backup_path)

    hook_path.write_text(
        _render_pre_push_hook_script(install_dir), encoding="utf-8", newline="\n"
    )
    hook_path.chmod(hook_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    print(f"  [install] Pre-push hook installed at {hook_path}")
    return hook_path


def write_wrapper_scripts(repo_root: Path) -> None:
    sh_path = repo_root / _WRAPPER_SH_NAME
    sh_path.write_text(_render_wrapper_sh(), encoding="utf-8", newline="\n")
    sh_path.chmod(sh_path.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    bat_path = repo_root / _WRAPPER_BAT_NAME
    bat_path.write_text(_render_wrapper_bat(), encoding="utf-8", newline="")

    print(f"  [install] Manual CLI ready: ./{_WRAPPER_SH_NAME} (or {_WRAPPER_BAT_NAME} on Windows)")


def remove_wrapper_scripts(repo_root: Path) -> bool:
    removed = False
    for name in (_WRAPPER_SH_NAME, _WRAPPER_BAT_NAME):
        path = repo_root / name
        if path.exists():
            path.unlink()
            removed = True
    return removed


