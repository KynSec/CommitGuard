def repo_info(target: str | Path, engine: str | Path | None = None) -> dict:
    repo = find_repo_root(target)
    engine_path = resolve_engine(repo, engine)
    branch = _git(repo, "rev-parse", "--abbrev-ref", "HEAD")
    remote = _git(repo, "remote", "get-url", "origin")
    remote_url = remote.stdout.strip() if remote.returncode == 0 else ""
    try:
        config = _load_config(repo)
        report_dir = config.report_dir
        config_summary = _config_summary(config)
        config_error = None
    except ActionError as exc:
        report_dir = DEFAULT_REPORT_DIR
        config_summary = None
        config_error = str(exc)
    try:
        from core import __version__ as version
    except Exception:  # noqa: BLE001  # pragma: no cover - broken install
        version = "unknown"
    return {
        "root": str(repo),
        "name": repo.name,
        "branch": branch.stdout.strip() if branch.returncode == 0 else "",
        "remote": remote_url,
        "github": parse_github_slug(remote_url),
        "installed": (repo / INSTALL_DIRNAME / "main.py").is_file(),
        "hook": _hook_state(repo),
        "config_path": str(repo / CONFIG_FILENAME),
        "config_exists": (repo / CONFIG_FILENAME).is_file(),
        "config_error": config_error,
        "config": config_summary,
        "baseline_exists": (repo / BASELINE_FILENAME).is_file(),
        "baseline_path": str(repo / BASELINE_FILENAME),
        "report_dir": str((repo / report_dir).resolve()),
        "engine": str(engine_path),
        "rules_dir": str(resolve_rules_dir(repo, engine_path)),
        "version": version,
    }


